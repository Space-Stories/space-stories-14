using System.Linq;
using Content.Shared._Stories.Blackjack;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Stories.Blackjack.UI;

public enum StoriesBlackjackCashierMode : byte
{
    Hidden,
    Locked,
    Held,
    Seated,
}

public readonly record struct StoriesBlackjackCashierView(
    string Chips,
    string Cash,
    string Held,
    bool ShowHeld,
    bool CanChip,
    bool CanMinus,
    bool CanReset,
    bool CanBuyCash,
    bool CanBuyCard,
    string BuyHint,
    bool CanCashOut,
    bool CanCashOutCard,
    bool CanCashOutAll,
    string CashOutHint,
    bool CanWithdraw,
    string DepositText);

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackCashier : PanelContainer
{
    private const string ArrowState = "arrow-right";
    private const int AmountDigits = 9;

    [Dependency] private IResourceCache _cache = default!;

    public event Action<int>? OnChip;
    public event Action<int>? OnStep;
    public event Action? OnReset;
    public event Action? OnAmountChanged;
    public event Action<BlackjackCashierOp>? OnOp;
    public event Action? OnCashOutAll;

    public StoriesBlackjackCashier()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        Frame.PanelOverride = MakePanel(StoriesBlackjackPalette.Gold.WithAlpha(0.35f), StoriesBlackjackPalette.Panel);
        BuyPanel.PanelOverride = MakePanel(StoriesBlackjackPalette.FeltBright.WithAlpha(0.6f), StoriesBlackjackPalette.Backdrop);
        CashOutPanel.PanelOverride = MakePanel(StoriesBlackjackPalette.Gold.WithAlpha(0.6f), StoriesBlackjackPalette.Backdrop);
        TitleLabel.FontColorOverride = StoriesBlackjackPalette.Gold;
        DepositLabel.FontColorOverride = StoriesBlackjackPalette.Text;
        HaveLabel.FontColorOverride = StoriesBlackjackPalette.Muted;
        AmountTitle.FontColorOverride = StoriesBlackjackPalette.Muted;
        PaintHeader(BuyFrom, BuyArrow, BuyTo, StoriesBlackjackPalette.FeltBright);
        PaintHeader(CashOutFrom, CashOutArrow, CashOutTo, StoriesBlackjackPalette.Gold);

        AmountEdit.IsValid = text => text.Length <= AmountDigits && text.All(char.IsAsciiDigit);
        AmountEdit.OnTextChanged += _ => OnAmountChanged?.Invoke();
        Chip5.OnPressed += _ => OnChip?.Invoke(Chip5.Value);
        Chip25.OnPressed += _ => OnChip?.Invoke(Chip25.Value);
        Chip100.OnPressed += _ => OnChip?.Invoke(Chip100.Value);
        Chip500.OnPressed += _ => OnChip?.Invoke(Chip500.Value);
        MinusButton.OnPressed += _ => OnStep?.Invoke(-1);
        PlusButton.OnPressed += _ => OnStep?.Invoke(1);
        ResetButton.OnPressed += _ => OnReset?.Invoke();
        BuyCashButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.BuyCash);
        BuyCardButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.BuyCard);
        CashOutButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.CashOut);
        CashOutCardButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.CashOutCard);
        CashOutAllButton.OnPressed += _ => OnCashOutAll?.Invoke();
        DepositButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.Deposit);
        WithdrawButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.Withdraw);
        SellHeldButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.SellHeld);
        SellHeldCardButton.OnPressed += _ => OnOp?.Invoke(BlackjackCashierOp.SellHeldCard);
    }

    public void SetMode(StoriesBlackjackCashierMode mode)
    {
        Visible = mode != StoriesBlackjackCashierMode.Hidden;
        LockedLabel.Visible = mode == StoriesBlackjackCashierMode.Locked;
        HeldBox.Visible = mode == StoriesBlackjackCashierMode.Held;
        SeatedBox.Visible = mode == StoriesBlackjackCashierMode.Seated;
    }

    public void SetHeldOnly(string text)
    {
        HeldOnlyLabel.SetMessage(FormattedMessage.FromUnformatted(text), defaultColor: StoriesBlackjackPalette.Text);
    }

    public void SetAmountText(string text)
    {
        if (AmountEdit.Text != text)
            AmountEdit.SetText(text);
    }

    public string GetAmountText()
    {
        return AmountEdit.Text;
    }

    public void SetSeated(StoriesBlackjackCashierView view)
    {
        ChipsBadge.Value = view.Chips;
        CashBadge.Value = view.Cash;
        HeldBadge.Visible = view.ShowHeld;
        HeldBadge.Value = view.Held;
        DepositBox.Visible = view.ShowHeld;
        DepositLabel.Text = view.DepositText;

        Chip5.Disabled = !view.CanChip;
        Chip25.Disabled = !view.CanChip;
        Chip100.Disabled = !view.CanChip;
        Chip500.Disabled = !view.CanChip;
        PlusButton.Disabled = !view.CanChip;
        MinusButton.Disabled = !view.CanMinus;
        ResetButton.Disabled = !view.CanReset;

        BuyCashButton.Disabled = !view.CanBuyCash;
        BuyCardButton.Disabled = !view.CanBuyCard;
        SetHint(BuyHint, view.BuyHint);
        CashOutButton.Disabled = !view.CanCashOut;
        CashOutCardButton.Disabled = !view.CanCashOutCard;
        CashOutAllButton.Disabled = !view.CanCashOutAll;
        SetHint(CashOutHint, view.CashOutHint);
        WithdrawButton.Disabled = !view.CanWithdraw;
    }

    private void PaintHeader(Label from, TextureRect arrow, Label to, Color color)
    {
        from.FontColorOverride = color;
        to.FontColorOverride = color;
        arrow.Texture = StoriesBlackjackArt.Icon(_cache, ArrowState);
        arrow.Modulate = color;
    }

    private static void SetHint(RichTextLabel label, string text)
    {
        label.Visible = text.Length > 0;
        if (text.Length > 0)
            label.SetMessage(FormattedMessage.FromUnformatted(text), defaultColor: StoriesBlackjackPalette.Muted);
    }

    private static StyleBoxFlat MakePanel(Color border, Color fill)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = fill,
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };
    }
}
