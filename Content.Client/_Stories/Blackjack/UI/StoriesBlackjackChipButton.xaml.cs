using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.Blackjack.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackChipButton : ContainerButton
{
    private const string RingState = "chip-ring";

    [Dependency] private IResourceCache _cache = default!;

    private int _value;
    private bool _loaded;

    public StoriesBlackjackChipButton()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        StyleBoxOverride = new StyleBoxEmpty();
        RingRect.Texture = StoriesBlackjackArt.Icon(_cache, RingState);
        _loaded = true;
        Apply();
    }

    public int Value
    {
        get => _value;
        set
        {
            _value = value;
            ChipRect.Texture = StoriesBlackjackArt.Icon(_cache, $"chip-{value}");
        }
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();

        Apply();
    }

    private void Apply()
    {
        if (!_loaded)
            return;

        var mode = DrawMode;
        RingRect.Visible = mode is DrawModeEnum.Hover or DrawModeEnum.Pressed;
        ChipRect.Modulate = mode switch
        {
            DrawModeEnum.Disabled => StoriesBlackjackPalette.ChipDisabled,
            DrawModeEnum.Pressed => StoriesBlackjackPalette.ChipPressed,
            _ => StoriesBlackjackPalette.IconTint,
        };
        DefaultCursorShape = mode == DrawModeEnum.Disabled ? CursorShape.Arrow : CursorShape.Hand;
    }
}
