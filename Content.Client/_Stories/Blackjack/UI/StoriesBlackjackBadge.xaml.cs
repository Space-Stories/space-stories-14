using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.Blackjack.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackBadge : PanelContainer
{
    [Dependency] private IResourceCache _cache = default!;

    public StoriesBlackjackBadge()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        Frame.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = StoriesBlackjackPalette.BadgeFill,
            BorderColor = StoriesBlackjackPalette.BadgeBorder,
            BorderThickness = new Thickness(1),
        };
        ValueLabel.FontColorOverride = StoriesBlackjackPalette.Text;
        CaptionLabel.FontColorOverride = StoriesBlackjackPalette.Muted;
    }

    public string Icon
    {
        set => IconRect.Texture = StoriesBlackjackArt.Icon(_cache, value);
    }

    public string Caption
    {
        set => CaptionLabel.Text = value;
    }

    public string Value
    {
        set => ValueLabel.Text = value;
    }
}
