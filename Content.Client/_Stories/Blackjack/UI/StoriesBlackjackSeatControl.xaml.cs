using System.Numerics;
using Content.Shared._Stories.Blackjack;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics.RSI;
using Robust.Shared.Input;
using Robust.Shared.Serialization.TypeSerializers.Implementations;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Stories.Blackjack.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackSeatControl : Control
{
    private const int NameLength = 9;
    private const int NameLimit = 10;
    private const int FrameSize = 56;
    private const int FrameOffset = 8;
    private const int AvatarOffset = 14;
    private const int AvatarTop = 6;
    private const int LampOffset = 44;
    private const int LampTop = -10;
    private const int CaptionTop = 57;

    private static readonly ResPath UiSprite = new("_Stories/Interface/Blackjack/ui.rsi");

    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IResourceCache _cache = default!;

    private readonly RSI _rsi;
    private int _freeFrame = -1;
    private bool _free;
    private bool _clickable;
    private bool _hovered;
    private bool _lampReady;
    private bool _lampVisible;
    private int _lampFrame = -1;

    public event Action? OnSit;

    public StoriesBlackjackSeatControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _rsi = _cache.GetResource<RSIResource>(SpriteSpecifierSerializer.TextureRoot / UiSprite).RSI;
        MouseFilter = MouseFilterMode.Pass;

        LayoutContainer.SetPosition(Frame, new Vector2(FrameOffset, 0));
        LayoutContainer.SetPosition(Avatar, new Vector2(AvatarOffset, AvatarTop));
        LayoutContainer.SetPosition(Highlight, new Vector2(FrameOffset, 0));
        LayoutContainer.SetPosition(Lamp, new Vector2(LampOffset, LampTop));
        LayoutContainer.SetPosition(Caption, new Vector2(0, CaptionTop));

        Avatar.OverrideDirection = Direction.South;
        Avatar.WorldRotation = Angle.Zero;
        Highlight.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.Transparent,
            BorderColor = StoriesBlackjackPalette.Gold,
            BorderThickness = new Thickness(2),
        };
        Highlight.Visible = false;
        Lamp.Visible = false;
        Avatar.Visible = false;
        Caption.FontColorOverride = StoriesBlackjackPalette.Text;
    }

    public void SetFree(bool clickable)
    {
        _free = true;
        _clickable = clickable;
        _freeFrame = -1;
        Avatar.Visible = false;
        Highlight.Visible = false;
        Lamp.Visible = false;
        _lampVisible = false;
        Caption.Text = clickable ? Loc.GetString("stories-blackjack-seat-sit") : Loc.GetString("stories-blackjack-seat-free");
        Caption.FontColorOverride = clickable ? StoriesBlackjackPalette.Gold : StoriesBlackjackPalette.Dim;
        DefaultCursorShape = clickable ? CursorShape.Hand : CursorShape.Arrow;
        UpdateFreeFrame();
    }

    public void SetTaken(BlackjackSeat seat, bool mine, bool showLamp)
    {
        _free = false;
        _clickable = false;
        _hovered = false;
        Frame.Modulate = Color.White;
        DefaultCursorShape = CursorShape.Arrow;
        Frame.Texture = _rsi["seat-taken"].GetFrame(RsiDirection.South, 0);
        Avatar.SetEntity(seat.Player);
        Avatar.Visible = true;
        Highlight.Visible = mine;
        Caption.Text = mine ? Loc.GetString("stories-blackjack-seat-you") : Truncate(seat.Name);
        Caption.FontColorOverride = mine ? StoriesBlackjackPalette.Gold : StoriesBlackjackPalette.Text;
        _lampVisible = showLamp;
        _lampReady = seat.Ready;
        _lampFrame = -1;
        Lamp.Visible = showLamp;
        UpdateLamp();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_free)
            UpdateFreeFrame();

        if (_lampVisible)
            UpdateLamp();
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Function != EngineKeyFunctions.UIClick || !_free || !_clickable)
            return;

        OnSit?.Invoke();
        args.Handle();
    }

    protected override void MouseEntered()
    {
        base.MouseEntered();

        _hovered = true;
        UpdateModulate();
    }

    protected override void MouseExited()
    {
        base.MouseExited();

        _hovered = false;
        UpdateModulate();
    }

    private void UpdateModulate()
    {
        if (!_free)
            return;

        Frame.Modulate = !_clickable ? Color.White.WithAlpha(0.4f) : _hovered ? Color.White : Color.White.WithAlpha(0.85f);
    }

    private void UpdateFreeFrame()
    {
        var state = _rsi["seat-free"];
        var frame = FrameAt(state, (float) _timing.RealTime.TotalSeconds);
        if (frame == _freeFrame)
            return;

        _freeFrame = frame;
        Frame.Texture = state.GetFrame(RsiDirection.South, frame);
        UpdateModulate();
    }

    private void UpdateLamp()
    {
        var state = _rsi[_lampReady ? "lamp-ready" : "lamp-wait"];
        var frame = FrameAt(state, (float) _timing.RealTime.TotalSeconds);
        if (frame == _lampFrame)
            return;

        _lampFrame = frame;
        Lamp.Texture = state.GetFrame(RsiDirection.South, frame);
    }

    private static int FrameAt(RSI.State state, float time)
    {
        if (state.DelayCount <= 1 || state.AnimationLength <= 0f)
            return 0;

        var position = time % state.AnimationLength;
        var accumulated = 0f;
        for (var i = 0; i < state.DelayCount; i++)
        {
            accumulated += state.GetDelay(i);
            if (position < accumulated)
                return i;
        }

        return state.DelayCount - 1;
    }

    private static string Truncate(string name)
    {
        return name.Length <= NameLimit ? name : name[..NameLength] + "…";
    }
}
