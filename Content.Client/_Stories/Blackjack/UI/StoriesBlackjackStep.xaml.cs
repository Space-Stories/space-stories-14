using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.Blackjack.UI;

public enum StoriesBlackjackStepState : byte
{
    Pending,
    Current,
    Done,
}

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackStep : PanelContainer
{
    private const string DoneIcon = "icon-check";
    private const string CurrentIcon = "arrow-right";

    private static readonly StyleBoxFlat PendingBox = MakeBox(StoriesBlackjackPalette.Panel, StoriesBlackjackPalette.StepIdleBorder, 1f);
    private static readonly StyleBoxFlat DoneBox = MakeBox(StoriesBlackjackPalette.Panel, StoriesBlackjackPalette.StepIdleBorder, 1f);
    private static readonly StyleBoxFlat CurrentBox = MakeBox(StoriesBlackjackPalette.StepCurrentFill, StoriesBlackjackPalette.Gold, 2f);

    [Dependency] private IResourceCache _cache = default!;

    public StoriesBlackjackStep()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void SetStep(string text, StoriesBlackjackStepState state)
    {
        TextLabel.Text = text;
        switch (state)
        {
            case StoriesBlackjackStepState.Current:
                Frame.PanelOverride = CurrentBox;
                TextLabel.FontColorOverride = StoriesBlackjackPalette.GoldBright;
                Marker.Texture = StoriesBlackjackArt.Icon(_cache, CurrentIcon);
                Marker.Modulate = StoriesBlackjackPalette.Gold;
                break;
            case StoriesBlackjackStepState.Done:
                Frame.PanelOverride = DoneBox;
                TextLabel.FontColorOverride = StoriesBlackjackPalette.Dim;
                Marker.Texture = StoriesBlackjackArt.Icon(_cache, DoneIcon);
                Marker.Modulate = Color.White;
                break;
            default:
                Frame.PanelOverride = PendingBox;
                TextLabel.FontColorOverride = StoriesBlackjackPalette.Muted;
                Marker.Texture = null;
                break;
        }
    }

    private static StyleBoxFlat MakeBox(Color fill, Color border, float thickness)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = fill,
            BorderColor = border,
            BorderThickness = new Thickness(thickness),
        };
    }
}
