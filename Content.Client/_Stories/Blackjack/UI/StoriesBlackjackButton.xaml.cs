using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.Blackjack.UI;

public enum StoriesBlackjackButtonVariant : byte
{
    Primary,
    Accent,
    Quiet,
    Link,
}

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackButton : ContainerButton
{
    private const int ModeCount = 4;
    private const int VariantCount = 4;
    private const float PaddingX = 12f;
    private const float PaddingY = 5f;

    private static readonly StyleBoxFlat[] Boxes = BuildBoxes();

    [Dependency] private IResourceCache _cache = default!;

    private StoriesBlackjackButtonVariant _variant;
    private string? _icon;
    private bool _loaded;

    public StoriesBlackjackButton()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _loaded = true;
        Apply();
    }

    public string Title
    {
        get => TitleLabel.Text ?? string.Empty;
        set => TitleLabel.Text = value;
    }

    public string? Subtitle
    {
        get => SubtitleLabel.Text;
        set
        {
            SubtitleLabel.Text = value;
            SubtitleLabel.Visible = !string.IsNullOrEmpty(value);
        }
    }

    public string? Icon
    {
        get => _icon;
        set
        {
            _icon = value;
            IconRect.Texture = value == null ? null : StoriesBlackjackArt.Icon(_cache, value);
            IconRect.Visible = value != null;
        }
    }

    public StoriesBlackjackButtonVariant Variant
    {
        get => _variant;
        set
        {
            _variant = value;
            Apply();
        }
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();

        Apply();
    }

    private void Apply()
    {
        if (!_loaded)
            return;

        var mode = (int) DrawMode;
        var colors = Colors(_variant)[mode];
        StyleBoxOverride = Boxes[(int) _variant * ModeCount + mode];
        TitleLabel.FontColorOverride = colors.Title;
        SubtitleLabel.FontColorOverride = colors.Subtitle;
        IconRect.Modulate = DrawMode == DrawModeEnum.Disabled ? StoriesBlackjackPalette.IconDisabled : StoriesBlackjackPalette.IconTint;
        Content.Margin = DrawMode == DrawModeEnum.Pressed
            ? new Thickness(PaddingX, PaddingY + 1f, PaddingX, PaddingY - 1f)
            : new Thickness(PaddingX, PaddingY);
        DefaultCursorShape = DrawMode == DrawModeEnum.Disabled ? CursorShape.Arrow : CursorShape.Hand;
    }

    private static StoriesBlackjackButtonColors[] Colors(StoriesBlackjackButtonVariant variant)
    {
        return variant switch
        {
            StoriesBlackjackButtonVariant.Primary => StoriesBlackjackPalette.PrimaryButton,
            StoriesBlackjackButtonVariant.Accent => StoriesBlackjackPalette.AccentButton,
            StoriesBlackjackButtonVariant.Link => StoriesBlackjackPalette.LinkButton,
            _ => StoriesBlackjackPalette.QuietButton,
        };
    }

    private static StyleBoxFlat[] BuildBoxes()
    {
        var boxes = new StyleBoxFlat[VariantCount * ModeCount];
        for (var variant = 0; variant < VariantCount; variant++)
        {
            var colors = Colors((StoriesBlackjackButtonVariant) variant);
            var top = variant == (int) StoriesBlackjackButtonVariant.Primary ? 2f : 1f;
            for (var mode = 0; mode < ModeCount; mode++)
            {
                boxes[variant * ModeCount + mode] = new StyleBoxFlat
                {
                    BackgroundColor = colors[mode].Fill,
                    BorderColor = colors[mode].Border,
                    BorderThickness = new Thickness(1f, top, 1f, 1f),
                };
            }
        }

        return boxes;
    }
}
