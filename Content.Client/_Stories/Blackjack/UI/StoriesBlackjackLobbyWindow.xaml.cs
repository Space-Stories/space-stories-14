using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Stories.Blackjack;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics.RSI;
using Robust.Shared.Serialization.TypeSerializers.Implementations;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Stories.Blackjack.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesBlackjackLobbyWindow : FancyWindow
{
    private const string TableState = "table";
    public const int SeatCount = 5;
    private const string ReadyIcon = "icon-check";
    private const int SeatHalf = 36;
    private const int SeatTop = 28;

    private static readonly Vector2[] SeatCentres =
    [
        new(44, 120),
        new(116, 184),
        new(192, 200),
        new(268, 184),
        new(340, 120),
    ];

    [Dependency] private IResourceCache _cache = default!;

    private readonly StoriesBlackjackSeatControl[] _seats = new StoriesBlackjackSeatControl[SeatCount];
    private readonly StoriesBlackjackStep[] _steps;

    public event Action<int>? OnSit;
    public event Action? OnReady;
    public event Action? OnLeave;
    public event Action? OnSpectate;
    public event Action? OnFrame;

    public StoriesBlackjackCashier Cashier => CashierPanel;

    public StoriesBlackjackLobbyWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _steps = [Step0, Step1, Step2];

        Backdrop.PanelOverride = new StyleBoxFlat(StoriesBlackjackPalette.Backdrop);
        TablePanel.PanelOverride = MakePanel(StoriesBlackjackPalette.Felt);
        StatusPanel.PanelOverride = MakePanel(StoriesBlackjackPalette.Gold);
        RulesPanel.PanelOverride = MakePanel(StoriesBlackjackPalette.Gold);
        WinsPanel.PanelOverride = MakePanel(StoriesBlackjackPalette.Gold);
        RulesTitle.FontColorOverride = StoriesBlackjackPalette.Gold;
        WinsTitle.FontColorOverride = StoriesBlackjackPalette.Gold;
        TimerLabel.FontColorOverride = StoriesBlackjackPalette.Gold;
        LimitsLabel.FontColorOverride = StoriesBlackjackPalette.Gold;

        LayoutContainer.SetPosition(TableImage, Vector2.Zero);
        for (var i = 0; i < SeatCount; i++)
        {
            var index = i;
            var seat = new StoriesBlackjackSeatControl { Visible = false };
            seat.OnSit += () => OnSit?.Invoke(index);
            _seats[i] = seat;
            TableLayout.AddChild(seat);
            LayoutContainer.SetPosition(seat, SeatCentres[i] - new Vector2(SeatHalf, SeatTop));
        }

        ReadyButton.OnPressed += _ => OnReady?.Invoke();
        LeaveButton.OnPressed += _ => OnLeave?.Invoke();
        SpectateButton.OnPressed += _ => OnSpectate?.Invoke();
    }

    public void SetTitle(string text)
    {
        Title = text;
    }

    public void SetTableSprite(ResPath sprite)
    {
        var rsi = _cache.GetResource<RSIResource>(SpriteSpecifierSerializer.TextureRoot / sprite).RSI;
        TableImage.Texture = rsi.TryGetState(TableState, out var state) ? state.GetFrame(RsiDirection.South, 0) : null;
    }

    public void SetSeatHidden(int index)
    {
        _seats[index].Visible = false;
    }

    public void SetSeatFree(int index, bool clickable)
    {
        var control = _seats[index];
        control.Visible = true;
        control.SetFree(clickable);
    }

    public void SetSeatTaken(int index, BlackjackSeat seat, bool mine, bool showLamp)
    {
        var control = _seats[index];
        control.Visible = true;
        control.SetTaken(seat, mine, showLamp);
    }

    public void SetStatus(string text)
    {
        StatusLabel.SetMessage(FormattedMessage.FromUnformatted(text), defaultColor: StoriesBlackjackPalette.Text);
    }

    public void SetTimerVisible(bool visible)
    {
        TimerLabel.Visible = visible;
    }

    public void SetTimerText(string text)
    {
        TimerLabel.Text = text;
    }

    public void SetSteps(bool visible)
    {
        StepsBox.Visible = visible;
    }

    public void SetStep(int index, string? text, StoriesBlackjackStepState state)
    {
        var step = _steps[index];
        step.Visible = text != null;
        if (text != null)
            step.SetStep(text, state);
    }

    public void SetButtons(bool readyVisible, string readyText, bool readyPrimary, bool readyIcon, bool leaveVisible, bool leaveDisabled, bool spectateVisible)
    {
        ReadyButton.Visible = readyVisible;
        ReadyButton.Title = readyText;
        ReadyButton.Variant = readyPrimary ? StoriesBlackjackButtonVariant.Primary : StoriesBlackjackButtonVariant.Quiet;
        ReadyButton.Icon = readyIcon ? ReadyIcon : null;
        LeaveButton.Visible = leaveVisible;
        LeaveButton.Disabled = leaveDisabled;
        SpectateButton.Visible = spectateVisible;
    }

    public void SetRules(string body, bool limitsVisible, string limits)
    {
        RulesBody.SetMessage(FormattedMessage.FromUnformatted(body), defaultColor: StoriesBlackjackPalette.Text);
        LimitsLabel.Visible = limitsVisible;
        if (limitsVisible)
            LimitsLabel.Text = limits;
    }

    public void SetWins(bool visible, IReadOnlyList<KeyValuePair<string, int>> rows)
    {
        WinsPanel.Visible = visible;
        if (!visible)
            return;

        WinsList.RemoveAllChildren();
        if (rows.Count == 0)
        {
            WinsList.AddChild(new Label
            {
                Text = Loc.GetString("stories-blackjack-wins-empty"),
                FontColorOverride = StoriesBlackjackPalette.Dim,
            });
            return;
        }

        foreach (var (name, count) in rows)
        {
            var row = new StoriesBlackjackWinRow();
            row.SetRow(name, count);
            WinsList.AddChild(row);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        OnFrame?.Invoke();
    }

    private static StyleBoxFlat MakePanel(Color accent)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = StoriesBlackjackPalette.Panel,
            BorderColor = accent.WithAlpha(0.35f),
            BorderThickness = new Thickness(1),
        };
    }
}
