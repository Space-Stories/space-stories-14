using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Stories.Heretic.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesHereticKnowledgeNodeControl : ContainerButton
{
    private static readonly ProtoId<ShaderPrototype> GreyscaleShader = "Greyscale";
    private static readonly ResPath KnowledgeRsi = new("/Textures/_Stories/Heretic/knowledge.rsi");

    private static readonly Color LockedColor = Color.FromHex("#6e6e74");
    private static readonly Color AvailableHintColor = Color.FromHex("#8fd18f");
    private static readonly Color LockedReasonColor = Color.FromHex("#d65a5a");

    private const float SealScale = 2f;
    private const float IconScale = 1.5f;
    private const float SealRadius = 31f;
    private const float PulseSpeed = 2.6f;

    [Dependency] private IPrototypeManager _proto = default!;

    public readonly StoriesHereticKnowledgeNode Node;
    private readonly StoriesHereticPalette _palette;
    private float _time;
    private float _pulse;

    public StoriesHereticKnowledgeNodeControl(StoriesHereticKnowledgeNode node)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Node = node;
        _palette = StoriesHereticPalette.Get(node.Path);

        var learned = node.State == StoriesHereticNodeState.Learned;
        var locked = node.State == StoriesHereticNodeState.Locked;
        var accent = locked ? LockedColor : _palette.Accent;

        StyleBoxOverride = new StyleBoxEmpty();
        Disabled = node.State != StoriesHereticNodeState.Available;
        DefaultCursorShape = Disabled ? CursorShape.Arrow : CursorShape.Hand;
        TooltipSupplier = _ => CreateTooltip();

        Seal.SetFromSpriteSpecifier(new SpriteSpecifier.Rsi(KnowledgeRsi, locked ? "node_locked" : _palette.NodeState));
        Seal.DisplayRect.TextureScale = new Vector2(SealScale);

        KnowledgeIcon.Visible = node.Icon != null;
        if (node.Icon != null)
        {
            KnowledgeIcon.SetFromSpriteSpecifier(node.Icon);
            KnowledgeIcon.DisplayRect.TextureScale = new Vector2(IconScale);
        }

        if (locked)
        {
            KnowledgeIcon.DisplayRect.ShaderOverride = _proto.Index(GreyscaleShader).Instance();
            KnowledgeIcon.Modulate = Color.FromHex("#9a9a9a");
            Seal.Modulate = Color.FromHex("#b0b0b0");
        }

        CheckBadge.Visible = learned;
        CheckBadge.PanelOverride = MakeBadge(accent);
        CheckLabel.FontColorOverride = accent;

        var nameColor = node.State switch
        {
            StoriesHereticNodeState.Learned => Color.FromHex("#f4ece0"),
            StoriesHereticNodeState.Available => Color.FromHex("#d6d6d6"),
            _ => Color.FromHex("#8a8a8f"),
        };
        NameLabel.SetMessage(FormattedMessage.FromUnformatted(node.Name), nameColor);

        CostLabel.Text = Loc.GetString("stories-heretic-ui-cost", ("cost", node.Cost));
        CostLabel.FontColorOverride = accent;
        CostBadge.PanelOverride = MakeBadge(accent);
    }

    public Vector2 SealCenter => (Vector2) (SealBox.GlobalPixelPosition - GlobalPixelPosition) + (Vector2) SealBox.PixelSize / 2f;

    public float SealPixelRadius => SealRadius * UIScale;

    private StyleBoxFlat MakeBadge(Color accent)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = _palette.Dark.WithAlpha(0.9f),
            BorderColor = accent.WithAlpha(0.7f),
            BorderThickness = new Thickness(1),
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (Node.State != StoriesHereticNodeState.Available)
            return;

        _time += args.DeltaSeconds;
        _pulse = 0.5f + 0.5f * MathF.Sin(_time * PulseSpeed);
        Seal.Modulate = IsHovered ? Color.White : Color.InterpolateBetween(Color.FromHex("#a8a8a8"), Color.White, _pulse);
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var glow = Node.State switch
        {
            StoriesHereticNodeState.Learned => 0.16f,
            StoriesHereticNodeState.Available => 0.04f + 0.12f * _pulse,
            _ => 0f,
        };

        if (IsHovered)
            glow += 0.1f;

        if (glow <= 0f)
            return;

        var color = Node.State == StoriesHereticNodeState.Locked ? LockedColor : _palette.Accent;
        var center = SealCenter;
        var radius = SealPixelRadius;

        for (var i = 3; i >= 1; i--)
        {
            handle.DrawCircle(center, radius + i * 3f * UIScale, color.WithAlpha(glow));
        }

        if (Node.State == StoriesHereticNodeState.Learned)
        {
            handle.DrawCircle(center, radius + 1f * UIScale, color, false);
            handle.DrawCircle(center, radius + 2f * UIScale, color, false);
        }
    }

    private Control CreateTooltip()
    {
        var message = new FormattedMessage();
        message.PushColor(_palette.Accent);
        message.AddText(Node.Name);
        message.Pop();
        message.PushNewline();
        message.AddText(Node.Description);
        message.PushNewline();
        message.AddText(Loc.GetString("stories-heretic-ui-tooltip-cost", ("cost", Node.Cost)));
        message.PushNewline();

        var (status, color) = Node.State switch
        {
            StoriesHereticNodeState.Learned => (Loc.GetString("stories-heretic-ui-learned"), _palette.Accent),
            StoriesHereticNodeState.Available => (Loc.GetString("stories-heretic-ui-available"), AvailableHintColor),
            _ => (Node.Reason ?? Loc.GetString("stories-heretic-ui-locked"), LockedReasonColor),
        };
        message.PushColor(color);
        message.AddText(status);
        message.Pop();

        var tooltip = new Tooltip { MaxWidth = 360 };
        tooltip.SetMessage(message);
        return tooltip;
    }
}
