using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.Heretic.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesHereticKnowledgeWindow : FancyWindow
{
    private static readonly Color BaseBackground = Color.FromHex("#141418");

    public event Action<string>? OnLearn;

    public StoriesHereticKnowledgeWindow()
    {
        RobustXamlLoader.Load(this);
        Tree.OnLearn += id => OnLearn?.Invoke(id);
    }

    public void UpdateState(int points,
        string? pathId,
        string pathName,
        string? ritualItems,
        IReadOnlyList<StoriesHereticKnowledgeColumn> columns,
        IReadOnlyList<StoriesHereticKnowledgeNode> nodes)
    {
        var palette = StoriesHereticPalette.Get(pathId);

        Backdrop.PanelOverride = new StyleBoxFlat(Color.InterpolateBetween(BaseBackground, palette.Dark, 0.35f));
        TreePanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.InterpolateBetween(BaseBackground, Color.Black, 0.4f),
            BorderColor = palette.Accent.WithAlpha(0.35f),
            BorderThickness = new Thickness(1),
        };
        PointsBadge.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.Dark,
            BorderColor = palette.Accent,
            BorderThickness = new Thickness(1),
        };

        PointsLabel.Text = Loc.GetString("stories-heretic-ui-points", ("points", points));
        PointsLabel.FontColorOverride = palette.Accent;
        PathLabel.Text = pathName;
        PathLabel.FontColorOverride = palette.Accent;

        RitualLabel.Visible = ritualItems != null;
        if (ritualItems != null)
            RitualLabel.Text = Loc.GetString("stories-heretic-ui-ritual", ("items", ritualItems));

        Tree.SetNodes(columns, nodes);
    }
}
