using System.Linq;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Stories.AssemblyBench.UI;

[GenerateTypedNameReferences]
public sealed partial class StoriesAssemblyBenchWindow : FancyWindow
{
    private StoriesAssemblyBenchView? _view;
    private bool _working;

    public event Action<int>? OnApply;

    public StoriesAssemblyBenchWindow()
    {
        RobustXamlLoader.Load(this);

        Backdrop.PanelOverride = new StyleBoxFlat(StoriesAssemblyBenchPalette.Backdrop);
        CanvasPanel.PanelOverride = MakePanel(StoriesAssemblyBenchPalette.Hologram);
        HintPanel.PanelOverride = MakePanel(StoriesAssemblyBenchPalette.Active);
        ProductPanel.PanelOverride = MakePanel(StoriesAssemblyBenchPalette.Hologram);
        StepLabel.FontColorOverride = StoriesAssemblyBenchPalette.Active;
        ProductLabel.FontColorOverride = StoriesAssemblyBenchPalette.Hologram;
        CompletedLabel.FontColorOverride = StoriesAssemblyBenchPalette.Done;

        Canvas.OnZonePressed += () =>
        {
            if (_view is { } view)
                OnApply?.Invoke(view.Current);
        };
    }

    public void UpdateState(StoriesAssemblyBenchView view)
    {
        _view = view;
        Canvas.SetState(view.Sprite, view.Steps.Select(s => s.Id).ToList(), view.Current, view.WorkEnd, view.WorkDuration);

        ProductView.SetPrototype(view.Result);
        ProductLabel.Text = view.ResultName;
        CompletedLabel.Text = Loc.GetString("stories-assembly-bench-completed", ("count", view.Completed));

        var rebuild = StepList.ChildCount != view.Steps.Count;
        if (rebuild)
            StepList.RemoveAllChildren();

        for (var i = 0; i < view.Steps.Count; i++)
        {
            var state = i < view.Current
                ? StoriesAssemblyBenchStepState.Done
                : i == view.Current
                    ? StoriesAssemblyBenchStepState.Current
                    : StoriesAssemblyBenchStepState.Pending;

            StoriesAssemblyBenchStepRow row;
            if (rebuild)
            {
                row = new StoriesAssemblyBenchStepRow();
                StepList.AddChild(row);
            }
            else
            {
                row = (StoriesAssemblyBenchStepRow) StepList.GetChild(i);
            }

            row.SetStep(view.Steps[i], state);
        }

        Progress.MaxValue = view.Steps.Count;
        Progress.Value = view.Current;
        ProgressLabel.Text = Loc.GetString("stories-assembly-bench-progress",
            ("step", Math.Min(view.Current + 1, view.Steps.Count)),
            ("total", view.Steps.Count));

        UpdateHint();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (Canvas.Working != _working)
            UpdateHint();
    }

    private void UpdateHint()
    {
        _working = Canvas.Working;

        if (_view is not { } view || view.Current >= view.Steps.Count)
            return;

        var step = view.Steps[view.Current];
        StepLabel.Text = step.Name;
        var hint = _working
            ? Loc.GetString("stories-assembly-bench-hint-working")
            : Loc.GetString(step.IsTool ? "stories-assembly-bench-hint-tool" : "stories-assembly-bench-hint-insert",
                ("item", step.Requirement));
        HintLabel.SetMessage(FormattedMessage.FromUnformatted(hint), StoriesAssemblyBenchPalette.Text);
    }

    private static StyleBoxFlat MakePanel(Color accent)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = StoriesAssemblyBenchPalette.Panel,
            BorderColor = accent.WithAlpha(0.35f),
            BorderThickness = new Thickness(1),
        };
    }
}
