using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Stories.AssemblyBench.UI;

public enum StoriesAssemblyBenchStepState : byte
{
    Pending,
    Current,
    Done,
}

[GenerateTypedNameReferences]
public sealed partial class StoriesAssemblyBenchStepRow : PanelContainer
{
    private const float PulseSpeed = 4f;

    private readonly StyleBoxFlat _box = new() { BorderThickness = new Thickness(3, 0, 0, 0) };
    private StoriesAssemblyBenchStepState _state;
    private float _time;

    public StoriesAssemblyBenchStepRow()
    {
        RobustXamlLoader.Load(this);
        PanelOverride = _box;
    }

    public void SetStep(StoriesAssemblyBenchStepView step, StoriesAssemblyBenchStepState state)
    {
        _state = state;

        var accent = state switch
        {
            StoriesAssemblyBenchStepState.Done => StoriesAssemblyBenchPalette.Done,
            StoriesAssemblyBenchStepState.Current => StoriesAssemblyBenchPalette.Active,
            _ => StoriesAssemblyBenchPalette.Dim,
        };

        Icon.SetPrototype(step.Icon);
        Icon.Modulate = state == StoriesAssemblyBenchStepState.Pending ? Color.White.WithAlpha(0.4f) : Color.White;

        Mark.Text = state switch
        {
            StoriesAssemblyBenchStepState.Done => "✔",
            StoriesAssemblyBenchStepState.Current => "▶",
            _ => string.Empty,
        };
        Mark.FontColorOverride = accent;

        NameLabel.Text = step.Name;
        NameLabel.FontColorOverride = state == StoriesAssemblyBenchStepState.Pending
            ? StoriesAssemblyBenchPalette.Dim
            : StoriesAssemblyBenchPalette.Text;

        RequirementLabel.Text = step.Requirement;
        RequirementLabel.FontColorOverride = accent;

        _box.BorderColor = state == StoriesAssemblyBenchStepState.Pending ? accent.WithAlpha(0.25f) : accent;
        _box.BackgroundColor = state == StoriesAssemblyBenchStepState.Pending ? Color.Transparent : accent.WithAlpha(0.12f);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state != StoriesAssemblyBenchStepState.Current)
            return;

        _time += args.DeltaSeconds;
        var pulse = 0.5f + 0.5f * MathF.Sin(_time * PulseSpeed);
        _box.BackgroundColor = StoriesAssemblyBenchPalette.Active.WithAlpha(0.1f + 0.14f * pulse);
    }
}
