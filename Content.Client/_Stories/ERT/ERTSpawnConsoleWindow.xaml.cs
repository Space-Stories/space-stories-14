using Content.Client.UserInterface.Controls;
using Content.Shared._Stories.ERT;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;

namespace Content.Client._Stories.ERT;

[GenerateTypedNameReferences]
public sealed partial class ERTSpawnConsoleWindow : FancyWindow
{
    [Dependency] private ILocalizationManager _loc = default!;

    public event Action<int>? OnCallPressed;

    public ERTSpawnConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        BalanceCard.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#1A1A1E"),
            BorderColor = Color.FromHex("#3A3A40"),
            BorderThickness = new Thickness(1),
        };
    }

    public void UpdateOptions(
        List<ERTSpawnOption> options,
        bool isOnCooldown,
        int activeIndex,
        int balance,
        bool hasAdminAccess,
        List<bool> canCall,
        LocId titleName,
        LocId balanceName)
    {
        Title = _loc.GetString(titleName);
        BalanceLabel.Text = _loc.GetString(balanceName);
        BalanceValueLabel.Text = balance.ToString();

        OptionsContainer.DisposeAllChildren();

        for (int i = 0; i < options.Count; i++)
        {
            var option = options[i];
            var index = i;

            var card = new PanelContainer();
            card.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1A1A1E"),
                BorderColor = Color.FromHex("#3A3A40"),
                BorderThickness = new Thickness(1),
            };

            if (isOnCooldown && index == activeIndex)
            {
                card.PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = Color.FromHex("#1A1A1E"),
                    BorderColor = Color.OrangeRed,
                    BorderThickness = new Thickness(2),
                };
            }

            var innerBox = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(8),
            };

            card.AddChild(innerBox);

            var nameLabel = new RichTextLabel { MaxWidth = 550, };
            nameLabel.SetMessage(_loc.GetString(option.Name));
            innerBox.AddChild(nameLabel);

            var descLabel = new RichTextLabel { MaxWidth = 550, };
            descLabel.SetMessage(_loc.GetString(option.Desc));
            innerBox.AddChild(descLabel);

            innerBox.AddChild(new Label { Text = $"Стоимость: {option.Price}" });
            if (option.RequiresAdminAllow && !hasAdminAccess)
            {
                innerBox.AddChild(new Label { Text = _loc.GetString("stories-ert-spawn-requires-admin-allow"), FontColorOverride = Color.OrangeRed, });
            }
            else if (option.Price > balance)
            {
                innerBox.AddChild(new Label { Text = _loc.GetString("stories-ert-spawn-low-balance"), FontColorOverride = Color.OrangeRed, });
            }
            else if (option.RequiresAdminAllow && hasAdminAccess)
            {
                innerBox.AddChild(new Label { Text = _loc.GetString("stories-ert-spawn-has-admin-access"), FontColorOverride = Color.Green, });
            }

            var callButton = new Button
            {
                Text = _loc.GetString("stories-ert-spawn-call-button"),
                Margin = new Thickness(0, 4, 0, 0),
                Disabled = isOnCooldown || !canCall[index],
            };

            callButton.OnPressed += _ => OnCallPressed?.Invoke(index);
            innerBox.AddChild(callButton);
            OptionsContainer.AddChild(card);
        }
    }
}