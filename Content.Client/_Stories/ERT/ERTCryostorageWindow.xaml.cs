using Content.Client.UserInterface.Controls;
using Content.Shared._Stories.ERT;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Serialization.TypeSerializers.Implementations;
using Robust.Shared.Utility;
using System.Numerics;

namespace Content.Client._Stories.ERT;

[GenerateTypedNameReferences]
public sealed partial class ERTCryostorageWindow : FancyWindow
{
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IResourceCache _resourceCache = default!;

    public event Action<int>? OnSpawnPressed;

    public ERTCryostorageWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateOptions(
        List<ERTCryostorageOption> options,
        LocId titleName,
        bool hasAdminAccess,
        bool blocked)
    {
        Title = _loc.GetString(titleName);

        OptionsContainer.DisposeAllChildren();

        for (int i = 0; i < options.Count; i++)
        {
            var index = i;
            var option = options[i];

            var card = new PanelContainer();
            card.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1A1A1E"),
                BorderColor = Color.FromHex("#3A3A40"),
                BorderThickness = new Thickness(1),
            };

            var innerBox = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(8),
            };
            card.AddChild(innerBox);

            var headerBox = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            var iconTexture = GetSpriteTexture(option.Sprite);
            if (iconTexture != null)
            {
                var icon = new TextureRect
                {
                    Texture = iconTexture,
                    SetSize = new Vector2(32, 32),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    VerticalAlignment = Control.VAlignment.Center,
                };
                headerBox.AddChild(icon);
            }

            headerBox.AddChild(new Label
            {
                Text = _loc.GetString(option.Name),
                FontColorOverride = Color.Gold,
                VerticalAlignment = Control.VAlignment.Center,
            });

            innerBox.AddChild(headerBox);

            if (option.RequiresAdminAllow && !hasAdminAccess)
            {
                innerBox.AddChild(new Label { Text = _loc.GetString("stories-ert-cryostorage-requires-admin-allow"), FontColorOverride = Color.OrangeRed, });
            }
            else if (option.RequiresAdminAllow)
            {
                innerBox.AddChild(new Label { Text = _loc.GetString("stories-ert-cryostorage-has-admin-access"), FontColorOverride = Color.Green, });
            }

            var canPress = true;
            if (option.RequiresAdminAllow && !hasAdminAccess)
                canPress = false;
            if (blocked)
                canPress = false;

            var wakeButton = new Button
            {
                Text = _loc.GetString("stories-ert-cryostorage-wake-button"),
                Margin = new Thickness(0, 4, 0, 0),
                Disabled = !canPress, 
            };

            wakeButton.OnPressed += _ => OnSpawnPressed?.Invoke(index);
            innerBox.AddChild(wakeButton);
            OptionsContainer.AddChild(card);
        }
    }

    private Texture? GetSpriteTexture(SpriteSpecifier sprite)
    {
        if (sprite is not SpriteSpecifier.Rsi rsi)
            return null;

        var rsiResource = _resourceCache.GetResource<RSIResource>(
            SpriteSpecifierSerializer.TextureRoot / rsi.RsiPath);
        if (rsiResource.RSI == null)
            return null;

        if (rsiResource.RSI.TryGetState(rsi.RsiState, out var rsiState))
            return rsiState.Frame0;

        return null;
    }
}